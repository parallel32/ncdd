                                                <div class="title">
                                                    <h2>Interstate Consequences</h2>
                                                </div>
                                                <p>Under the Driver's License Compact, member States must communicate the fact of a conviction for DUI to the "Home State". The "Home State" then takes action against the license under its own laws. Forty-five States are currently members of the Interstate Compact. Out of State convictions count. Under all but a few geographical exceptions, it will be impossible for an out of State resident to avoid serious consequences in their home state.</p>
