                                                <div class="title">
                                                    <h2>Erwin-Taylor Award</h2>
                                                </div>
                                                <p>The Erwin-Taylor Award was first called the Richard E. Erwin Lifetime Achievement Award. It was named after Richard E. Erwin, the author of the first text on defending DUIs. Richard Erwin published the first handbook on how to defend a DUI case in 1963. A public defender for most of his career, he had to create tools and strategies for fighting DUI cases. In 2004, the name changed to the Erwin-Taylor award to also honor Larry Taylor, who authored several important DUI manuals to help train the DUI practitioner.</p>
